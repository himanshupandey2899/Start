# String Indexing

str0 = input("Enter Your Value: ") #"Python"

# Positive Indexing
print(str0)     # Output: 'Python'
print(str0[0])  # Output: 'P'
print(str0[1])  # Output: 'y'
print(str0[2])  # Output: 't'
print(str0[3])  # Output: 'h'
print(str0[4])  # Output: 'o'
print(str0[5])  # Output: 'n'

# Negative Indexing
print(str0[-1])  # Output: 'n'
print(str0[-2])  # Output: 'o'
print(str0[-3])  # Output: 'h'
print(str0[-4])  # Output: 't'
print(str0[-5])  # Output: 'y'
print(str0[-6])  # Output: 'P'