# String Basics

str1 = input("Enter Your Value: ") # "Welcome to"
str2 = input("Enter Your Value: ") # "Maple"
str3 = input("Enter Your Value: ") # "World"

print(str1) # Output: 'Welcome to'
print(str2) # Output: 'Maple'
print(str3) # Output: 'World'

# String Concatenation

print(str1 + " " + str2 + " " + str3) # Output: 'Welcome to Maple World'

# Length of a String

print(len(str1)) # Output: 10
print(len(str2)) # Output: 5
print(len(str3)) # Output: 5
print(len(str1 + " " + str2 + " " + str3)) # Output: 21