# Program to take input from the user and print it

print("A sample program to understand user input method in Python")  # Printing a message to the user

name = input("Enter your good name: ")  # Taking input from the user and storing it in a variable called 'name'

age = input("Enter your age: ")  # Taking input from the user and storing it in a variable called 'age'

print("Hello, " , name , "!" , "\n" , "Your age is " , age)  # Printing a greeting message with the user's name and age

print("Hello, " + name , "!" + "\n" , "Your age is " + age)  # Printing a greeting message with the user's name and age

print("Hello, " + name , "!" , "\n" , "Your age is " , age)  # Printing a greeting message with the user's name and age

